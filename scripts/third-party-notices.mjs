// Writes THIRD-PARTY-NOTICES.md: the licenses of everything built into the program, which have to
// go with it. Needs cargo-about, and `pnpm install` having been run in app.
//   node scripts/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const run = (command, args, cwd) =>
  execFileSync(command, args, { cwd, encoding: "utf8", maxBuffer: 1 << 28, shell: process.platform === "win32" });
const tidy = (text) => text.replaceAll("\r\n", "\n").trim();

/** Each distinct license text, with what uses it. */
const groups = new Map();
function add(name, license, text) {
  const key = `${license}\n${tidy(text)}`;
  if (!groups.has(key)) groups.set(key, { license, text: tidy(text), users: new Set() });
  groups.get(key).users.add(name);
}

// Rust
const about = JSON.parse(run("cargo", ["about", "generate", "--format", "json", "-c", "about.toml", "-m", "app/src-tauri/Cargo.toml", "--offline"], root));
const ours = /^(hk-|hackerman)/;
for (const license of about.licenses) {
  for (const { crate } of license.used_by) {
    if (!ours.test(crate.name)) add(`${crate.name} ${crate.version}`, license.id, license.text);
  }
}

// What the page is built from
const packages = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"], path.join(root, "app")));
for (const [license, entries] of Object.entries(packages)) {
  for (const entry of entries) {
    for (const [index, version] of entry.versions.entries()) {
      const folder = entry.paths[index];
      const file = existsSync(folder)
        ? readdirSync(folder).find((name) => /^(licen[cs]e|copying|notice)/i.test(name))
        : undefined;
      const text = file ? readFileSync(path.join(folder, file), "utf8") : `Licensed under ${license}.`;
      add(`${entry.name} ${version}`, license, text);
    }
  }
}

const sorted = [...groups.values()].sort((a, b) => a.license.localeCompare(b.license));
const count = new Set(sorted.flatMap((group) => [...group.users])).size;
let notices = `# Third-party notices

Hackerman is built from ${count} open-source components, listed here with their licenses. It's
generated by \`scripts/third-party-notices.mjs\`.
`;
for (const group of sorted) {
  const users = [...group.users].sort((a, b) => a.localeCompare(b)).join(", ");
  notices += `\n---\n\n## ${group.license}\n\nUsed by: ${users}\n\n\`\`\`text\n${group.text.replaceAll("```", "'''")}\n\`\`\`\n`;
}
writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), notices);
console.log(`${count} components, ${groups.size} license texts, ${Math.round(notices.length / 1024)} KB`);
